export const countryMap = new Map(countries.map((country) => [country.code, country]));

const normalize = (value = '') =>
  value
    .toString()
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s🇦-🇿🏴]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const distance = (a, b) => {
  const dp = Array.from({ length: a.length + 1 }, () => Array(b.length + 1).fill(0));
  for (let i = 0; i <= a.length; i += 1) dp[i][0] = i;
  for (let j = 0; j <= b.length; j += 1) dp[0][j] = j;
  for (let i = 1; i <= a.length; i += 1) {
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + cost);
    }
  }
  return dp[a.length][b.length];
};

export function findCountry(input = '') {
  const clean = normalize(input);
  if (!clean) return null;

  const exact = countries.find((country) => {
    const names = [country.name, country.code, country.emoji, ...country.aliases].map(normalize);
    return names.includes(clean);
  });
  if (exact) return exact;

  const contains = countries.find((country) => {
    const names = [country.name, ...country.aliases].map(normalize);
    return names.some((name) => clean.includes(name) || name.includes(clean));
  });
  if (contains) return contains;

  let best = null;
  let bestScore = Infinity;
  countries.forEach((country) => {
    [country.name, ...country.aliases].map(normalize).forEach((candidate) => {
      if (!candidate || candidate.length < 3) return;
      const score = distance(clean, candidate);
      if (score < bestScore) {
        bestScore = score;
        best = country;
      }
    });
  });

  return bestScore <= Math.max(2, Math.floor(clean.length * 0.28)) ? best : null;
}

export function countryByEmoji(input = '') {
  return countries.find((country) => input.includes(country.emoji)) || null;
}

export function randomCountries(count = 16) {
  return [...countries].sort(() => Math.random() - 0.5).slice(0, count);
}
